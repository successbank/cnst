// 제품별 세부 사양에 따른 추가 설명
function getAdditionalDescription($product) {
    $spec = $product['specifications'];
    $additional = '';
    
    // 크기나 두께 정보 추출
    if (preg_match('/(\d+)×(\d+)/', $spec, $matches)) {
        $size1 = $matches[1];
        $size2 = $matches[2];
        $additional .= "\n\n본 제품은 {$size1}mm × {$size2}mm 규격으로, ";
        
        if ($size1 < 50) {
            $additional .= "소형 구조물이나 세부 부재 제작에 적합합니다.";
        } elseif ($size1 < 150) {
            $additional .= "중형 구조물이나 일반 건축물에 널리 사용됩니다.";
        } else {
            $additional .= "대형 구조물이나 중량물 지지 구조에 적합합니다.";
        }
    }
    
    return $additional;
}

// 모든 활성 제품 가져오기
$stmt = $pdo->query("SELECT id, product_name, category_code, specifications FROM products WHERE is_active = 1");
$products = $stmt->fetchAll();

$updated = 0;
$errors = 0;

foreach ($products as $product) {
    $category = $product['category_code'];
    
    if (isset($category_templates[$category])) {
        $template = $category_templates[$category];
        
        // 기본 설명에 제품별 추가 설명 더하기
        $description = $template['description'] . getAdditionalDescription($product);
        $features = $template['features'];
        
        // 업데이트 쿼리
        $updateStmt = $pdo->prepare("
            UPDATE products 
            SET detailed_description = ?, 
                key_features = ?,
                updated_at = NOW()
            WHERE id = ?
        ");
        
        try {
            $updateStmt->execute([$description, $features, $product['id']]);
            $updated++;
            echo "Updated product ID {$product['id']}: {$product['product_name']}\n";
        } catch (Exception $e) {
            $errors++;
            echo "Error updating product ID {$product['id']}: " . $e->getMessage() . "\n";
        }
    }
}

echo "\n=== Update Complete ===\n";
echo "Total products updated: $updated\n";
echo "Errors: $errors\n";
